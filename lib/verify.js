'use strict';
/**
 * Big Bounty — Verification & Classification layer (DETECT -> VERIFY -> CORRELATE -> SCORE).
 *
 * This runs AFTER the existing scan modules and is purely additive: it never changes
 * what the modules do, it re-interprets their findings with evidence-aware judgement.
 *
 * Goals:
 *   1. Fingerprint WAF/CDN/CAPTCHA/challenge/block/proxy-error responses so a block
 *      page is never reported as proof of an application vulnerability.
 *   2. Give every finding an explicit lifecycle STATUS and CONFIDENCE, and make
 *      severity depend on evidence quality — not just "a payload caused a response".
 *   3. Correlate/de-duplicate noisy endpoint-discovery output into one useful
 *      attack-surface observation.
 *   4. Produce a structured coverage model instead of a single opaque percentage.
 *
 * All core functions are pure (no network, no side effects) so they can be unit
 * tested against real report data. runVerification() is the orchestrator.
 */

// ---------------------------------------------------------------------------
// Taxonomy
// ---------------------------------------------------------------------------
const STATUS = {
  DISCOVERED: 'endpoint_discovered',
  ACCESSIBLE: 'endpoint_accessible',
  BLOCKED: 'endpoint_blocked_protected',
  SUSPICIOUS: 'suspicious_behavior_detected',
  SUSPECTED: 'vulnerability_suspected',
  VERIFIED: 'vulnerability_verified',
  CONFIRMED: 'vulnerability_confirmed',
  MANUAL: 'manual_verification_required',
  NOT_TESTED: 'not_tested',
  OBSERVED: 'observed', // directly-observed config facts (headers, cors, dns…)
};

const CONFIDENCE = {
  CONFIRMED: 'confirmed',
  HIGH: 'high_confidence',
  LIKELY: 'likely',
  POSSIBLE: 'possible',
  INFORMATIONAL: 'informational',
  BLOCKED: 'blocked',
  NOT_TESTED: 'not_tested',
  REJECTED: 'false_positive_rejected',
};

const SEV_RANK = { critical: 5, high: 4, medium: 3, low: 2, info: 1, unknown: 1 };

// Finding tools whose "vulnerability" verdict can be an edge/WAF artifact rather
// than real application behaviour — these get evidence-aware scrutiny.
const ACTIVE_PROBE_TOOLS = new Set([
  'xxe', 'blind-sqli', 'sqli', 'ssrf', 'cmd-inj', 'command', 'rce', 'ssti',
  'lfi', 'rfi', 'path-traversal', 'traversal', 'redirect', 'crlf', 'host-header',
  'zap-fuzzer', 'intruder', 'burp-intruder', 'burp-repeater', 'smuggling',
  'request-smuggling', 'cache-poison', 'proto-pollution',
]);

// Tools that enumerate attack surface (collapsed into one observation).
const DISCOVERY_TOOLS = new Set([
  'dirlist', 'dirbust', 'dirs', 'kiterunner', 'ffuf', 'burp-intruder', 'intruder',
  'content-discovery', 'endpoint-discovery',
]);

// Directly-observed configuration facts — high confidence, not probe-dependent.
const OBSERVED_TOOLS = new Set([
  'headers', 'header-audit', 'cors', 'tls', 'ssl', 'cookies', 'dns', 'doh',
  'fingerprint', 'tech', 'secrets', 'rdap', 'crt.sh', 'spf', 'dmarc', 'waf',
  'http-probe', 'referer', 'sourcemap-detector', 'js-reverser',
]);

// Tests that genuinely require credentials the user did not supply.
const CREDENTIAL_DEPENDENT = [
  'authenticated session handling', 'logout invalidation', 'privilege separation',
  'horizontal authorization (IDOR/BOLA)', 'vertical authorization',
  'method-level authorization', 'authenticated API authorization',
];

