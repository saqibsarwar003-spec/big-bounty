/**
 * Fingerprint an HTTP response. Returns { isChallenge, vendor, kind, signal }.
 * Any of status / headers / body may be missing — it uses what it has.
 */
function fingerprintResponse({ status = 0, headers = {}, body = '' } = {}) {
  const h = {};
  for (const k of Object.keys(headers || {})) h[k.toLowerCase()] = headers[k];
  const text = typeof body === 'string' ? body : '';
  for (const sig of CHALLENGE_SIGNATURES) {
    // header match
    for (const [hk, hre] of (sig.header || [])) {
      const v = h[hk];
      if (v != null && hre.test(String(v))) {
        return { isChallenge: true, vendor: sig.vendor, kind: sig.kind, signal: `header ${hk}` };
      }
    }
    // body match
    for (const re of (sig.body || [])) {
      if (text && re.test(text)) {
        return { isChallenge: true, vendor: sig.vendor, kind: sig.kind, signal: `body ~ ${re.source.slice(0, 40)}` };
      }
    }
    // status-only (rate limit)
    if (sig.status && sig.status.includes(Number(status)) && !text) {
      return { isChallenge: true, vendor: sig.vendor, kind: sig.kind, signal: `status ${status}` };
    }
  }
  return { isChallenge: false, vendor: null, kind: null, signal: null };
}

// ---------------------------------------------------------------------------
// Evidence extraction — normalize the two finding schemas + inline objects
// ---------------------------------------------------------------------------
function extractResponse(finding) {
  const ev = finding.evidence || {};
  const status = Number(
    ev.statusCode != null ? ev.statusCode
    : ev.status != null ? ev.status
    : ev.httpStatus != null ? ev.httpStatus
    : (String(finding.title || '').match(/\bHTTP\s*(\d{3})\b/) || [])[1]
    || 0
  );
  const bodyFields = [ev.matchSnippet, ev.errorSnippet, ev.match, ev.snippet, ev.context, ev.body, ev.responseBody, ev.evidence];
  let bodyText = '';
  for (const f of bodyFields) { if (typeof f === 'string' && f.length > bodyText.length) bodyText = f; }
  return { status, bodyText };
}

function sevName(s) { return (typeof s === 'string' && SEV_RANK[s]) ? s : 'info'; }
function lower(x) { return String(x || '').toLowerCase(); }
function isVerifiedFileRead(txt) {
  // genuine /etc/passwd or Windows SAM style content, not a generic word match
  return /root:.?:0:0:/.test(txt) || /\[(extensions|fonts)\]/i.test(txt) || /;\s*for 16-bit app support/i.test(txt);
}

// ---------------------------------------------------------------------------
// Classify a single finding (pure)
// ---------------------------------------------------------------------------
function classifyFinding(finding, ctx = {}) {
  const f = { ...finding };
  const tool = lower(f.tool);
  const title = lower(f.title);
  const sev = sevName(f.severity);
  const resp = extractResponse(f);
  const fp = fingerprintResponse({ status: resp.status, headers: {}, body: resp.bodyText });
  const rootChallenged = !!(ctx.rootFingerprint && ctx.rootFingerprint.isChallenge);
  const wafPresent = !!ctx.wafPresent || rootChallenged;
  const blockStatus = [401, 403, 406, 429, 501, 502, 503].includes(resp.status);

  let status, confidence, why;
  let newSev = sev;

  const isDiscovery = DISCOVERY_TOOLS.has(tool) || /discovered (api )?endpoint|content discovery/i.test(title);
  const isActive = ACTIVE_PROBE_TOOLS.has(tool) || /xxe|sql injection|ssrf|command inj|template inj|traversal|rce|lfi|smuggl|crlf/i.test(title);
  const isObserved = OBSERVED_TOOLS.has(tool) && !isActive;

  if (isDiscovery) {
    // Endpoint discovery: discovered / accessible / blocked — never a vuln by itself.
    if (resp.status === 200) { status = STATUS.ACCESSIBLE; confidence = CONFIDENCE.HIGH; why = 'Endpoint responded 200 — reachable. Reachable ≠ vulnerable; needs its own test.'; newSev = SEV_RANK[sev] > SEV_RANK.low ? 'low' : sev; }
    else if (fp.isChallenge || blockStatus) { status = STATUS.BLOCKED; confidence = CONFIDENCE.BLOCKED; why = `Endpoint returned ${resp.status || 'a block'}${fp.vendor ? ` (${fp.vendor} ${fp.kind})` : ''} — protected/blocked, not an exposure.`; newSev = 'info'; }
    else { status = STATUS.DISCOVERED; confidence = CONFIDENCE.INFORMATIONAL; why = 'Endpoint path observed during discovery; no access or vulnerability established.'; newSev = SEV_RANK[sev] > SEV_RANK.low ? 'low' : sev; }
  } else if (isActive && SEV_RANK[sev] >= SEV_RANK.medium) {
    // Active-probe "vulnerability" — scrutinize the evidence.
    if (fp.isChallenge) {
      status = STATUS.BLOCKED; confidence = CONFIDENCE.REJECTED; newSev = 'info';
      why = `Response was a ${fp.vendor} ${fp.kind} page (${fp.signal}${resp.status ? `, HTTP ${resp.status}` : ''}). The payload "match" reflects the block page, not application behaviour — rejected as a false positive.`;
    } else if (blockStatus && wafPresent) {
      status = STATUS.BLOCKED; confidence = CONFIDENCE.REJECTED; newSev = 'info';
      why = `Probe returned HTTP ${resp.status} on a target fronted by ${ctx.wafVendor || 'a WAF/edge'} (root also challenges automated requests). Treated as an edge block, not an application vulnerability.`;
    } else if (tool === 'xxe' && !isVerifiedFileRead(resp.bodyText)) {
      status = STATUS.MANUAL; confidence = CONFIDENCE.POSSIBLE; newSev = 'low';
      why = 'XXE signature matched but no verified external-entity content (e.g. /etc/passwd contents) was returned. The detection regex is broad enough to match ordinary responses — manual verification required before treating as a vulnerability.';
    } else if (wafPresent) {
      status = STATUS.MANUAL; confidence = CONFIDENCE.POSSIBLE; newSev = SEV_RANK[sev] >= SEV_RANK.high ? 'medium' : 'low';
      why = `Active-probe result on a WAF/edge-protected target (${ctx.wafVendor || 'edge detected'}); response may be an edge artifact. Down-ranked to a lead pending manual verification.`;
    } else {
      // Plausible real finding with its own non-block evidence — keep, but mark as suspected (not "confirmed").
      status = STATUS.SUSPECTED; confidence = CONFIDENCE.LIKELY;
      why = 'Payload produced anomalous application behaviour that is not a known block/challenge page. Treat as a strong lead; confirm with a focused manual test before reporting as confirmed.';
    }
  } else if (isObserved) {
    status = STATUS.OBSERVED;
    confidence = sev === 'info' ? CONFIDENCE.INFORMATIONAL : CONFIDENCE.HIGH;
    why = 'Directly observed from the response/DNS/TLS metadata — high confidence; no active exploitation involved.';
  } else {
    // default: keep as-is, informational confidence
    status = sev === 'info' ? STATUS.OBSERVED : STATUS.SUSPECTED;
    confidence = sev === 'info' ? CONFIDENCE.INFORMATIONAL : CONFIDENCE.LIKELY;
    why = 'Classified from module output; no block/challenge signature detected in captured evidence.';
  }

  f.severity = newSev;
  if (newSev !== sev) f.originalSeverity = sev;
  f.status = status;
  f.confidence = confidence;
  f.whyClassified = why;
  f.sourceModule = f.tool || 'unknown';
  if (fp.isChallenge) f.edgeFingerprint = { vendor: fp.vendor, kind: fp.kind, signal: fp.signal };
  return f;
}

// ---------------------------------------------------------------------------
// Correlate / de-duplicate (pure)
// ---------------------------------------------------------------------------
function normTitle(t) { return lower(t).replace(/\b(\d{1,5}|0x[0-9a-f]+)\b/g, '#').replace(/['"`].*?['"`]/g, 'X').replace(/\s+/g, ' ').trim(); }

function correlateFindings(classified) {
  const surface = [];
  const kept = [];
  const seen = new Map(); // dedup key -> index in kept

  for (const f of classified) {
    const tool = lower(f.tool);
    const isDiscovery = DISCOVERY_TOOLS.has(tool) || /discovered (api )?endpoint/i.test(lower(f.title));
    // Collapse blocked/discovered surface items; keep genuinely accessible ones visible.
    if (isDiscovery && (f.status === STATUS.BLOCKED || f.status === STATUS.DISCOVERED)) {
      surface.push(f);
      continue;
    }
    const key = `${tool}|${normTitle(f.title)}|${lower(f.url)}`;
    if (seen.has(key)) {
      const idx = seen.get(key);
      kept[idx].occurrences = (kept[idx].occurrences || 1) + 1;
      continue;
    }
    seen.set(key, kept.length);
    kept.push(f);
  }

  if (surface.length) {
    const blocked = surface.filter((s) => s.status === STATUS.BLOCKED);
    const discovered = surface.filter((s) => s.status === STATUS.DISCOVERED);
    const sample = surface.slice(0, 25).map((s) => {
      const r = extractResponse(s);
      const path = (s.url || (s.evidence && (s.evidence.route || s.evidence.path)) || (String(s.title).match(/\/[^\s)]+/) || [''])[0] || '').toString().slice(0, 120);
      return { path, status: r.status || undefined, tool: s.tool };
    });
    kept.push({
      id: 'surface-' + Math.random().toString(36).slice(2, 10),
      tool: 'attack-surface',
      sourceModule: 'correlation',
      severity: 'info',
      status: STATUS.DISCOVERED,
      confidence: CONFIDENCE.INFORMATIONAL,
      title: `Attack surface: ${surface.length} endpoints probed — ${blocked.length} blocked/protected (401/403/WAF), ${discovered.length} discovered, 0 shown accessible`,
      whyClassified: `Collapsed ${surface.length} individual endpoint-discovery results into one observation. Blocked/protected endpoints are not exposures; they are edge/access-control responses. Reachable endpoints (if any) are listed separately.`,
      evidence: { total: surface.length, blocked: blocked.length, discovered: discovered.length, sample },
      remediation: 'Review that discovered paths should exist publicly; ensure protected endpoints enforce authorization at the application layer, not only at the edge.',
      collapsedFrom: surface.length,
    });
  }
  return kept;
}

// ---------------------------------------------------------------------------
// Coverage model (pure)
// ---------------------------------------------------------------------------
function categoryOf(tool) {
  const t = lower(tool);
  if (['dns', 'doh', 'rdap', 'crt.sh', 'recon', 'subdomains', 'spf', 'dmarc', 'http-probe', 'dirlist', 'dirs', 'kiterunner', 'ffuf', 'burp-intruder', 'intruder', 'attack-surface', 'osint'].some((x) => t.includes(x))) return 'attackSurface';
  if (['kiterunner', 'api', 'graphql', 'websocket', 'openapi', 'swagger'].some((x) => t.includes(x))) return 'api';
  if (['browser', 'browserbot', 'dom'].some((x) => t.includes(x))) return 'browser';
  if (['headers', 'header-audit', 'cors', 'tls', 'ssl', 'cookies', 'cache', 'secrets', 'fingerprint', 'tech', 'referer', 'sourcemap'].some((x) => t.includes(x))) return 'config';
  return 'application';
}

function buildCoverage(phases, finalFindings) {
  phases = Array.isArray(phases) ? phases : [];
  const executed = phases.filter((p) => p.status === 'ok').length;
  const failed = phases.filter((p) => p.status === 'error' || p.status === 'err').length;
  const skipped = phases.filter((p) => p.status === 'skipped').length;
  const planned = phases.length;

  let blocked = 0, manual = 0, verified = 0;
  const byCategory = {};
  for (const f of finalFindings) {
    if (f.status === STATUS.BLOCKED) blocked++;
    if (f.status === STATUS.MANUAL) manual++;
    if (f.status === STATUS.VERIFIED || f.status === STATUS.CONFIRMED) verified++;
    const c = categoryOf(f.tool);
    byCategory[c] = (byCategory[c] || 0) + 1;
  }

  return {
    model: 'structured',
    planned, executed, failed, skipped,
    notApplicable: 0,
    blockedFindings: blocked,
    manualVerificationRequired: manual,
    verified,
    credentialDependentNotRun: CREDENTIAL_DEPENDENT.length,
    credentialDependentTests: CREDENTIAL_DEPENDENT,
    byCategory,
    note: `${executed}/${planned} test phases executed`
      + (failed ? `, ${failed} failed` : '')
      + (skipped ? `, ${skipped} skipped (time budget)` : '')
      + `, ${blocked} finding(s) were edge/WAF-blocked, ${manual} need manual verification, `
      + `${CREDENTIAL_DEPENDENT.length} credential-dependent tests not run (no credentials supplied).`,
  };
}

// ---------------------------------------------------------------------------
// Orchestrator
// ---------------------------------------------------------------------------
function runVerification(result, opts = {}) {
  const r = { ...result };
  const findings = Array.isArray(r.findings) ? r.findings : [];
  const main = opts.mainResponse || {};
  const rootFingerprint = fingerprintResponse({ status: main.status, headers: main.headers, body: main.body });

  // WAF presence: root challenge, OR a "WAF/edge detected" finding from redteam.
  const wafFinding = findings.find((f) => lower(f.tool) === 'waf' || /edge\/waf detected|waf detected/i.test(lower(f.title)));
  const wafVendor = rootFingerprint.vendor
    || (wafFinding && (wafFinding.evidence && (wafFinding.evidence.detection || wafFinding.evidence.vendor)))
    || (wafFinding && (String(wafFinding.title).match(/detected:\s*([A-Za-z0-9 /]+)/) || [])[1])
    || null;
  const ctx = { rootFingerprint, wafPresent: rootFingerprint.isChallenge || !!wafFinding, wafVendor };

  const classified = findings.map((f) => classifyFinding(f, ctx));
  const correlated = correlateFindings(classified);

  // Recompute severity summary from the corrected findings.
  const summary = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  for (const f of correlated) summary[sevName(f.severity)] = (summary[sevName(f.severity)] || 0) + 1;

  const reclassified = classified.filter((f) => f.originalSeverity).length;
  const collapsed = classified.length - correlated.length + (correlated.some((f) => f.tool === 'attack-surface') ? 1 : 0);

  r.findings = correlated;
  r.summary = summary;
  r.coverageModel = buildCoverage(r.phases, correlated);
  r.verification = {
    engine: 'DETECT->VERIFY->CORRELATE->SCORE',
    wafPresent: ctx.wafPresent,
    wafVendor: ctx.wafVendor || undefined,
    rootChallenge: rootFingerprint.isChallenge ? { vendor: rootFingerprint.vendor, kind: rootFingerprint.kind } : undefined,
    findingsIn: findings.length,
    findingsOut: correlated.length,
    reclassified,
    falsePositivesRejected: classified.filter((f) => f.confidence === CONFIDENCE.REJECTED).length,
    collapsedIntoSurface: Math.max(0, collapsed),
  };
  return r;
}

module.exports = {
  STATUS, CONFIDENCE, CREDENTIAL_DEPENDENT,
  fingerprintResponse, classifyFinding, correlateFindings, buildCoverage, runVerification,
  extractResponse, // exported for tests
};
